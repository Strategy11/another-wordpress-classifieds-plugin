/**
 * Plugin integration for Yoast SEO plugin.
 *
 * @since x.x
 */
class AWPCP_YoastSEOPluginIntegration {

    /**
     * @since x.x
     */
    public function setup() {
        add_filter( 'awpcp-should-generate-rel-canonical', array( $this, 'should_generate_rel_canonical' ) );
    }

    /**
     * Let Yoast SEO print the only canonical URL when it is active.
     *
     * @since x.x
     *
     * @param bool $should Whether AWPCP should generate the rel canonical tag.
     *
     * @return bool
     */
    public function should_generate_rel_canonical( $should ) {
        if ( ! defined( 'WPSEO_VERSION' ) ) {
            return $should;
        }

        add_filter( 'wpseo_canonical', array( $this, 'filter_canonical' ) );

        return false;
    }

    /**
     * Use the listing URL as canonical URL on the Show Ad page.
     *
     * @since x.x
     *
     * @param string $canonical The canonical URL generated by Yoast SEO.
     *
     * @return string
     */
    public function filter_canonical( $canonical ) {
        $awpcp_canonical_url = awpcp_rel_canonical_url();

        if ( $awpcp_canonical_url ) {
            return $awpcp_canonical_url;
        }

        return $canonical;
    }
}
